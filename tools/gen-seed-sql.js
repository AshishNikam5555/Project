#!/usr/bin/env node
// Generates supabase/seed.sql from js/seed.js so demo mode and the database never drift apart.
// Usage: node tools/gen-seed-sql.js
const fs = require('fs');
const path = require('path');
const seed = require('../js/seed.js');

const q = v => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const j = v => `${q(JSON.stringify(v))}::jsonb`;
const t = { ...seed.tenant, private_config: { notify_whatsapp: (process.env.ADMIN_WHATSAPP || '+918668859522').split(',') } };
const out = [];
out.push('-- GENERATED by tools/gen-seed-sql.js from js/seed.js — do not edit by hand.');
out.push('begin;');
out.push(`insert into public.tenants (id, slug, name, config, private_config) values (${q(t.id)}, ${q(t.slug)}, ${q(t.name)}, ${j(t.config)}, ${j(t.private_config)})
  on conflict (id) do update set slug = excluded.slug, name = excluded.name, config = excluded.config, private_config = excluded.private_config;`);
for (const d of seed.doctors) {
  out.push(`insert into public.doctors (id, tenant_id, name, name_mr, role, role_mr, qualification, experience_years, photo_url, fee_inr, active, sort)
  values (${[d.id, t.id, d.name, d.name_mr, d.role, d.role_mr, d.qualification, d.experience_years, d.photo_url, d.fee_inr, d.active, d.sort].map(q).join(', ')})
  on conflict (id) do update set name = excluded.name, name_mr = excluded.name_mr, role = excluded.role, role_mr = excluded.role_mr, active = excluded.active;`);
}
for (const c of seed.categories) {
  out.push(`insert into public.service_categories (id, tenant_id, name, name_mr, sort) values (${[c.id, t.id, c.name, c.name_mr, c.sort].map(q).join(', ')})
  on conflict (id) do update set name = excluded.name, name_mr = excluded.name_mr, sort = excluded.sort;`);
}
for (const s of seed.services) {
  out.push(`insert into public.services (id, tenant_id, category_id, name, name_mr, duration_min, kind, bookable, active, sort)
  values (${[s.id, t.id, s.category_id, s.name, s.name_mr, s.duration_min, s.kind, s.bookable, s.active, s.sort].map(q).join(', ')})
  on conflict (id) do update set name = excluded.name, name_mr = excluded.name_mr, kind = excluded.kind, bookable = excluded.bookable, active = excluded.active;`);
  for (const d of s.doctor_ids)
    out.push(`insert into public.doctor_services (tenant_id, doctor_id, service_id) values (${q(t.id)}, ${q(d)}, ${q(s.id)}) on conflict do nothing;`);
}
out.push(`delete from public.availability where tenant_id = ${q(t.id)};`);
for (const a of seed.availability) {
  out.push(
    `insert into public.availability (tenant_id, doctor_id, weekday, start_time, end_time, slot_min) values (${[t.id, a.doctor_id, a.weekday, a.start_time, a.end_time, a.slot_min].map(q).join(', ')});`
  );
}
out.push('commit;', '');
fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), out.join('\n'));
console.log(`Wrote supabase/seed.sql (${out.length} statements)`);
